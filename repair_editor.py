#!/usr/bin/env python3
import re

# 读取文件
with open('/home/hongb/.openclaw/workspace/webbot/static/editor.html', 'r', encoding='utf-8') as f:
    content = f.read()

print(f"文件大小: {len(content)} 字符")

# 查找 addGCWebHeaderFooter 函数的开始和结束
# 函数开始于 "function addGCWebHeaderFooter(content) {"
# 我们需要找到对应的结束括号
lines = content.split('\n')
in_function = False
function_start = -1
function_end = -1
brace_count = 0

for i, line in enumerate(lines):
    if 'function addGCWebHeaderFooter(content)' in line:
        in_function = True
        function_start = i
        brace_count = 0
        # 计算当前行的左括号
        brace_count += line.count('{')
        brace_count -= line.count('}')
        print(f"找到函数开始于行 {i}: {line[:50]}...")
        continue
    
    if in_function:
        brace_count += line.count('{')
        brace_count -= line.count('}')
        
        if brace_count == 0:
            function_end = i
            print(f"找到函数结束于行 {i}")
            break

if function_start == -1 or function_end == -1:
    print("❌ 无法找到函数边界")
    exit(1)

print(f"函数范围: 行 {function_start} 到 {function_end}")

# 提取函数内容
function_lines = lines[function_start:function_end+1]
original_function = '\n'.join(function_lines)
print(f"原函数长度: {len(original_function)} 字符")
print(f"原函数前200字符:\n{original_function[:200]}")

# 分析问题
print("\n=== 问题分析 ===")

# 1. 检查是否有嵌套的 cleanContent 函数
if 'function cleanContent' in original_function:
    print("❌ 问题: addGCWebHeaderFooter 函数内部包含了 cleanContent 函数定义")
    
# 2. 检查 webBotHeader 和 webBotFooter
if 'const webBotHeader' in original_function:
    print("❌ 问题: 函数中包含 webBotHeader 定义 (应该只包含 GCWeb 头尾)")
    
if 'const webBotFooter' in original_function:
    print("❌ 问题: 函数中包含 webBotFooter 定义 (应该只包含 GCWeb 头尾)")

# 3. 检查反斜杠换行符
if '\\\\\\n' in original_function or '\\\n' in original_function:
    print("⚠️  注意: 函数中包含反斜杠换行符，可能导致字符串拼接问题")

# 创建新的简化函数
print("\n=== 创建新的简化函数 ===")

new_function = '''        function addGCWebHeaderFooter(content) {
            if (!content || typeof content !== 'string') return content;
            
            // Extract main content if needed
            let mainContent = extractMainContent(content);
            
            // Simple GCWeb header
            const gcwebHeader = '<header id="gcweb-header">' +
                '<div class="container">' +
                '<div class="row">' +
                '<div class="col-md-12">' +
                '<h1>Canada.ca Page Preview</h1>' +
                '<p class="text-muted">Composing mode - Showing main content with GCWeb theme</p>' +
                '</div>' +
                '</div>' +
                '</div>' +
                '</header>' +
                '<main class="container"><div class="row"><div class="col-md-12">';
            
            // Simple GCWeb footer
            const gcwebFooter = '</div></div></main>' +
                '<footer id="gcweb-footer" class="bg-light py-3 mt-4">' +
                '<div class="container">' +
                '<div class="row">' +
                '<div class="col-md-12 text-center">' +
                '<p class="mb-0">Canada.ca Government of Canada</p>' +
                '<p class="text-muted small">Preview generated by WebBot Editor</p>' +
                '</div>' +
                '</div>' +
                '</div>' +
                '</footer>';
            
            return gcwebHeader + mainContent + gcwebFooter;
        }'''

print(f"新函数长度: {len(new_function)} 字符")

# 替换原函数
print("\n=== 替换原函数 ===")
lines[function_start:function_end+1] = [new_function]

new_content = '\n'.join(lines)

# 保存修改
with open('/home/hongb/.openclaw/workspace/webbot/static/editor.html', 'w', encoding='utf-8') as f:
    f.write(new_content)

print("✅ 文件已更新")

# 验证修改
with open('/home/hongb/.openclaw/workspace/webbot/static/editor.html', 'r', encoding='utf-8') as f:
    updated = f.read()
    
if 'function addGCWebHeaderFooter' in updated:
    print("✅ 验证: addGCWebHeaderFooter 函数存在")
    
# 检查是否还有嵌套的 cleanContent 函数
if updated.count('function cleanContent') > 1:
    print(f"⚠️  警告: cleanContent 函数有重复定义 ({updated.count('function cleanContent')} 次)")

print("\n=== 修复完成 ===")
print("新的 addGCWebHeaderFooter 函数:")
print(new_function[:300] + "...")

# 也复制到前端目录
frontend_path = '/home/hongb/.openclaw/workspace/webbot/frontend/editor.html'
with open(frontend_path, 'w', encoding='utf-8') as f:
    f.write(new_content)
print(f"✅ 已复制到前端目录: {frontend_path}")